import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createIssue, issueForm, labelDefinitions, types, validateIssue } from './issue-policy.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const [command, ...args] = process.argv.slice(2);
const option = name => {
  const index = args.indexOf(name);
  if (index < 0) return undefined;
  if (!args[index + 1] || args[index + 1].startsWith('--')) throw new Error(`Missing value for ${name}`);
  return args[index + 1];
};
const input = () => {
  const file = option('--input');
  if (!file) throw new Error('--input <JSON file> is required');
  return JSON.parse(readFileSync(file, 'utf8').replace(/^\uFEFF/, ''));
};
const gh = (arguments_, stdin) => execFileSync('gh', arguments_, { encoding: 'utf8', input: stdin, stdio: ['pipe', 'pipe', 'pipe'] });
const repository = () => option('--repo') ?? 'litzio/litzio';

try {
  if (command === 'forms') {
    const { dump } = await import('js-yaml');
    for (const type of Object.keys(types)) {
      const file = path.join(root, '.github', 'ISSUE_TEMPLATE', `${type}.yml`);
      const expected = `# Generated by pnpm issues:forms; edit scripts/issue-policy.mjs.\n${dump(issueForm(type), { lineWidth: -1, noRefs: true })}`;
      if (args.includes('--check')) {
        if (readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== expected) throw new Error(`${type}.yml is stale; run pnpm issues:forms`);
      } else writeFileSync(file, expected);
    }
    console.log(args.includes('--check') ? 'Issue forms match the shared definition.' : 'Issue forms generated.');
  } else if (command === 'create') {
    const issue = createIssue(input());
    if (args.includes('--publish')) {
      const labelArgs = issue.labels.flatMap(label => ['--label', label]);
      const url = gh(['issue', 'create', '--repo', repository(), '--title', issue.title, '--body-file', '-', ...labelArgs], issue.body).trim();
      console.log(url);
      const published = JSON.parse(gh(['issue', 'view', url, '--repo', repository(), '--json', 'title,body,labels']));
      const errors = validateIssue(published).errors;
      if (errors.length || issue.labels.some(name => !published.labels.some(label => label.name === name))) {
        throw new Error(`Created ${url}, but verification failed. Inspect this issue before retrying.\n${errors.join('\n')}`);
      }
    } else console.log(JSON.stringify(issue, null, 2));
  } else if (command === 'check') {
    const result = validateIssue(input());
    if (result.errors.length) throw new Error(result.errors.join('\n'));
    console.log('Issue meets the title, type and required-field rules.');
  } else if (command === 'labels') {
    if (!args.includes('--apply')) console.log(JSON.stringify(labelDefinitions, null, 2));
    else for (const label of labelDefinitions) {
      gh(['label', 'create', label.name, '--repo', repository(), '--color', label.color, '--description', label.description, '--force']);
      console.log(label.name);
    }
  } else throw new Error('Usage: issues.mjs forms [--check] | create --input file.json [--publish] [--repo owner/repo] | check --input issue.json | labels [--apply] [--repo owner/repo]');
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
